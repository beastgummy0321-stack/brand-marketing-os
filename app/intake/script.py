def _known_facts_block(draft: dict) -> str:
    lines = ["【已知事實】"]
    if draft.get("description"):
        lines.append(f"- 業主描述：{draft['description']}")
    for imp in draft.get("scan_impressions") or []:
        lines.append(f"- （看起來像{imp['looks_like']}）{imp['title']}：{imp['content']}")
    if len(lines) == 1:
        lines.append("- （目前沒有額外的初掃資料，請完全依你自己查到的資料進行。）")
    return "\n".join(lines)


def _my_answers_block(draft: dict) -> str:
    answers = draft.get("answers") or []
    if not answers:
        return "【我的回答】\n（這次沒有回答額外的問題，請依你查到的資料自行判斷。）"
    lines = ["【我的回答】"]
    for a in answers:
        lines.append(f"- {a['question']}\n  我選：{a['choice_label']}" + (f"（補充：{a['note']}）" if a.get("note") else ""))
    return "\n".join(lines)


def _clip(text: str, limit: int = 100) -> str:
    text = (text or "").strip()
    return text if len(text) <= limit else text[:limit] + "…"


def confirmed_data_block(existing: dict) -> str:
    """重新調研用：已確認的品牌資料摘要（issue #1）。

    existing：{"brand_facts": [(label, value)], "product_facts": [(product, label, value)],
               "rules": [content], "claims": [(type_label, text)]}——全空時回空字串。"""
    lines = []
    for label, value in existing.get("brand_facts") or []:
        lines.append(f"- 品牌事實／{label}：{_clip(value)}")
    for product, label, value in existing.get("product_facts") or []:
        lines.append(f"- 產品事實（{product}）／{label}：{_clip(value)}")
    for content in existing.get("rules") or []:
        lines.append(f"- 限制規則：{_clip(content)}")
    for type_label, text in existing.get("claims") or []:
        lines.append(f"- 宣稱（{type_label}）：{_clip(text)}")
    if not lines:
        return ""
    return ("【已確認的品牌資料——既成事實，不用重查】\n"
            "以下是品牌方已逐條確認過的資料。視為既成事實：不得質疑、不用重新查證、"
            "總結表不用重複收錄。這次調研聚焦在以上還沒涵蓋的缺口。\n" + "\n".join(lines))


